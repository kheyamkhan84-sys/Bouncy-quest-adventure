export function getWorldForLevel(levelNumber: number): WorldDefinition {
  const clamped = Math.max(1, Math.min(1000, levelNumber));
  const worldIndex = Math.floor((clamped - 1) / 20);
  return WORLDS[worldIndex] || WORLDS[0];
}

export function getLevelIndexInWorld(levelNumber: number): number {
  const clamped = Math.max(1, Math.min(1000, levelNumber));
  return ((clamped - 1) % 20) + 1; // 1 to 20
}
